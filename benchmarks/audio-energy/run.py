#!/usr/bin/env python3
"""Counterbalanced real-time codec comparison. Preserves results, deletes only its generated media."""
import argparse,json,random,subprocess,pathlib,time,statistics
p=argparse.ArgumentParser();p.add_argument('--bench',required=True);p.add_argument('--output',type=pathlib.Path,required=True);p.add_argument('--seconds',type=float,default=30);p.add_argument('--rounds',type=int,default=3);p.add_argument('--fast',action='store_true');a=p.parse_args()
a.output=a.output.resolve()
a.output.mkdir(parents=True,exist_ok=True);schemes=['baseline','float32','pcm16','alac','aac64','aac96'];random.Random(1909).shuffle(schemes)
with (a.output/'results.jsonl').open('x') as log:
 for r in range(a.rounds):
  order=schemes[r:]+schemes[:r]
  if r%2:order.reverse()
  for scheme in order:
   directory=a.output/f'media-{r}-{scheme}'
   print(f'{time.strftime("%H:%M:%S")} round={r+1} scheme={scheme}',flush=True)
   command=[a.bench,scheme,str(a.seconds),'fast' if a.fast else 'realtime',str(directory)]
   result=json.loads(subprocess.check_output(command,text=True));result['round']=r+1
   log.write(json.dumps(result)+'\n');log.flush()
   print(f"  {result['energy_mw']:.3f} mW, {result['cpu_percent_one_core']:.3f}% CPU, {result['output_bytes']/1e6:.2f} MB",flush=True)
   # Files live in a unique experiment folder and were generated by this invocation.
   for path in result['paths']:pathlib.Path(path).unlink()
   directory.rmdir()
print('Completed',flush=True)
