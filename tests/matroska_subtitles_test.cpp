// Writes the fixture (or arbitrary bytes) to a private temporary file, since
// both entry points take a path -- they own their own descriptor by design.
class TemporaryFile final {
 public:
  explicit TemporaryFile(std::span<const unsigned char> bytes) {
    std::string pattern =
        (std::filesystem::temp_directory_path() / "wam_subs_XXXXXX").string();
    std::vector<char> buffer(pattern.begin(), pattern.end());
    buffer.push_back('\0');
    const int descriptor = ::mkstemp(buffer.data());
    if (descriptor < 0)
      return;
    path_ = buffer.data();
    if (!bytes.empty()) {
      const ssize_t written =
          ::write(descriptor, bytes.data(), bytes.size());
      ok_ = written == static_cast<ssize_t>(bytes.size());
    } else {
      ok_ = true;
    }
    ::close(descriptor);
  }

  ~TemporaryFile() {
    if (!path_.empty()) {
      std::error_code ignored;
      std::filesystem::remove(path_, ignored);
    }
  }

  TemporaryFile(const TemporaryFile&) = delete;
  TemporaryFile& operator=(const TemporaryFile&) = delete;

  [[nodiscard]] const std::filesystem::path& path() const noexcept {
    return path_;
  }
  [[nodiscard]] bool ok() const noexcept { return ok_; }

 private:
  std::filesystem::path path_;
  bool ok_{false};
};

