int failures = 0;

void expect(bool condition, const char* message) {
  if (!condition) {
    std::cerr << "FAIL: " << message << '\n';
    ++failures;
  }
}

void expectText(const std::string& actual, const std::string& expected,
                const char* message) {
  if (actual != expected) {
    std::cerr << "FAIL: " << message << "\n  expected [" << expected
              << "]\n  actual   [" << actual << "]\n";
    ++failures;
  }
}

