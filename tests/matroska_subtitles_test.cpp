// Records every read as a [offset, end) range, so a test can say exactly which
// regions of the file a pass touched.
class CountingReader final : public matroska::SeekableByteReader {
 public:
  explicit CountingReader(std::span<const unsigned char> bytes)
      : bytes_(bytes) {}

  [[nodiscard]] std::uint64_t size() const noexcept override {
    return bytes_.size();
  }

  [[nodiscard]] bool readAt(std::uint64_t offset,
                            std::span<std::byte> destination) noexcept override {
    if (offset > bytes_.size() || destination.size() > bytes_.size() - offset)
      return false;
    reads.emplace_back(offset, offset + destination.size());
    std::memcpy(destination.data(), bytes_.data() + offset, destination.size());
    return true;
  }

  std::vector<std::pair<std::uint64_t, std::uint64_t>> reads;

 private:
  std::span<const unsigned char> bytes_;
};

// Every Cluster's DATA range in the fixture. A Cluster's own element header
// lies before its data offset, so reading the header is not "descending into"
// the Cluster -- reading a byte inside the data range is.
std::vector<std::pair<std::uint64_t, std::uint64_t>> clusterDataRanges(
    std::span<const unsigned char> bytes) {
  std::vector<std::pair<std::uint64_t, std::uint64_t>> ranges;
  for (std::size_t i = 0; i + 5 <= bytes.size(); ++i) {
    if (bytes[i] != 0x1F || bytes[i + 1] != 0x43 || bytes[i + 2] != 0xB6 ||
        bytes[i + 3] != 0x75) {
      continue;
    }
    const unsigned char first = bytes[i + 4];
    if (first == 0)
      continue;
    unsigned width = 1;
    unsigned char mask = 0x80;
    while ((first & mask) == 0) {
      mask = static_cast<unsigned char>(mask >> 1);
      ++width;
    }
    if (i + 4 + width > bytes.size())
      continue;
    std::uint64_t size = static_cast<std::uint64_t>(first & (mask - 1));
    for (unsigned b = 1; b < width; ++b)
      size = (size << 8) | bytes[i + 4 + b];
    const std::uint64_t dataOffset = static_cast<std::uint64_t>(i) + 4 + width;
    // Reject a coincidental byte match inside a payload.
    if (size == 0 || dataOffset + size > bytes.size())
      continue;
    ranges.emplace_back(dataOffset, dataOffset + size);
    i = static_cast<std::size_t>(dataOffset + size) - 1;
  }
  return ranges;
}

void testHeaderPassStaysOutOfClusters() {
  // The header inventory is what the Subtitles menu is built from, so it runs
  // on every Matroska open. It must stay O(header). The demuxer's own
  // pre-admission pass exists precisely because descending into Clusters cost
  // 3,030,956 reads on a 1.9 GiB file; a subtitle menu that reintroduced that
  // walk would undo that fix in a different place.
  //
  // Pinned by exactly the boundary the demuxer's own read-count test pins: not
  // one byte inside any Cluster's DATA range may be read. Everything the
  // inventory needs -- the EBML header, Info and Tracks -- lies outside those
  // ranges, and a Cluster is skipped in O(1) by its declared size. The
  // assertion is independent of file size and of page-cache state.
  const auto clusters = clusterDataRanges(fixture());
  expect(!clusters.empty(),
         "the fixture contains at least one Cluster to bound the pass");

  CountingReader reader(fixture());
  const SubtitleTrackInventory inventory =
      inspectMatroskaSubtitleTracks(reader);
  expect(inventory.valid && inventory.tracks.size() == 3,
         "the measured pass is the real one and found all three tracks");

  std::uint64_t insideCluster = 0;
  for (const auto& read : reader.reads) {
    for (const auto& cluster : clusters) {
      if (read.first < cluster.second && read.second > cluster.first)
        ++insideCluster;
    }
  }
  expect(insideCluster == 0,
         "the subtitle header pass reads no byte inside any Cluster");
  // Also bound the absolute cost, so a change that starts re-reading the
  // header repeatedly is caught even while it stays outside the Clusters.
  // Measured: 507 reads on this 2,131-byte fixture, 692 on a 3.5 MB one and
  // 9,555 on a 1.9 GiB one -- the count tracks the number of top-level
  // elements, not the number of Blocks, which is the property that matters.
  expect(reader.reads.size() < 1'024,
         "the subtitle header pass costs a bounded number of reads");

  // The contrast that gives the assertion above its meaning: the cue load, by
  // design, DOES read inside the Clusters -- which is exactly why it is lazy,
  // runs only on an explicit track selection, and runs on a worker thread.
  CountingReader loadReader(fixture());
  const SubtitleTrackLoad load =
      loadMatroskaSubtitleTrack(loadReader, 1, subtitles::TextCodec::SubRip);
  expect(load.ok && load.cues.size() == 5,
         "the control load reads the same track successfully");
  std::uint64_t loadInsideCluster = 0;
  for (const auto& read : loadReader.reads) {
    for (const auto& cluster : clusters) {
      if (read.first < cluster.second && read.second > cluster.first)
        ++loadInsideCluster;
    }
  }
  expect(loadInsideCluster > 0,
         "the cue load does read inside Clusters, unlike the header pass");
}

